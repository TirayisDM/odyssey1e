//! odyssey1e — Tauri commands.
//!
//! Every command here is a thin wrapper: pull the token out of state,
//! call one thing in `supabase`, hand the result back. Rules logic does
//! not belong in this file. When the dice roller lands it goes in its
//! own module with its own tests, and a command calls it.
//!
//! Commands are deliberately NOT async — Tauri runs sync commands on a
//! thread pool, so the blocking HTTP in `supabase` is fine here and the
//! code stays readable.

mod character;
mod dice;
mod narrative;
mod supabase;

use character::{Resolved, Sheet};
use dice::{RandomRoller, RollResult};
use serde_json::{json, Value};
use supabase::{AppState, Session};
use tauri::State;

/* ============================ AUTH ============================ */

#[tauri::command]
fn sign_up(
    state: State<AppState>,
    email: String,
    password: String,
    display_name: String,
) -> Result<Session, String> {
    let s = supabase::sign_up(&email, &password, &display_name)?;
    state.set(Some(s.clone()))?;
    Ok(s)
}

#[tauri::command]
fn sign_in(state: State<AppState>, email: String, password: String) -> Result<Session, String> {
    let s = supabase::sign_in(&email, &password)?;
    state.set(Some(s.clone()))?;
    Ok(s)
}

#[tauri::command]
fn sign_out(state: State<AppState>) -> Result<(), String> {
    state.set(None)
}

/// Who am I, or null. Lets the frontend render without guessing.
#[tauri::command]
fn me(state: State<AppState>) -> Result<Option<Session>, String> {
    state.current()
}

/* ============================ GAMES ============================ */

/// Every game I am a member of. The DM sees theirs because the
/// on_game_created trigger seats them as a member; without it this
/// would return nothing for the person who made the game.
#[tauri::command]
fn list_games(state: State<AppState>) -> Result<Value, String> {
    let token = state.token()?;
    supabase::rest_get(
        &token,
        "games",
        &[("select", "id,name,join_code,is_open,created_at"), ("order", "created_at.desc")],
    )
}

#[tauri::command]
fn create_game(state: State<AppState>, name: String) -> Result<Value, String> {
    let session = state
        .current()?
        .ok_or_else(|| "not signed in".to_string())?;
    // join_code is generated by the column default; dm_uid must be us or
    // the insert policy rejects it.
    supabase::rest_insert(
        &session.access_token,
        "games",
        &json!({ "name": name, "dm_uid": session.user_id }),
    )
}

/// The only way into a game. See migration 001 — game_members has no
/// INSERT policy at all, on purpose.
#[tauri::command]
fn join_game(state: State<AppState>, code: String) -> Result<Value, String> {
    let token = state.token()?;
    supabase::rpc(&token, "join_game", &json!({ "p_code": code }))
}

#[tauri::command]
fn list_members(state: State<AppState>, game_id: String) -> Result<Value, String> {
    let token = state.token()?;
    supabase::rest_get(
        &token,
        "game_members",
        &[
            ("select", "profile_id,role,joined_at"),
            ("game_id", &format!("eq.{}", game_id)),
        ],
    )
}

